def L(speaker, text, src=(), ped=None):
    return {"type": "line", "speaker": speaker, "text": text, "source": list(src),
            "ped": (not src) if ped is None else ped, "blocked": None, "new": True}


def R(ref):
    """Reuse one approved beat verbatim (same text → same voice clip), e.g. R("002:ch12-s02#6")."""
    return {"reuse": ref}


def P(sec, reason="балдар ойлонот"):
    return {"type": "pause", "seconds": sec, "reason": reason}


def V(sec, description):
    return {"type": "visual", "seconds": sec, "description": description}


