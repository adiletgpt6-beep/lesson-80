#!/usr/bin/env python3
"""Generate Remotion data for a rework lesson: video/src/lessons/lR0N/{meta,boardPlans,scenePlan,index}.ts.

Boards and illustration cutaways are inherited from the approved lessons through the `origin` of each scene/beat
(lessons/R0N/script/chapters + origin.json); new scenes take their boards from video/src/lessons/rework/newBoards.ts.
Run after compose.py and `LESSON=R0N lesson_script.py timeline`.
"""
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
SRC = REPO / "production/vid-002/video/src/lessons"
sys.path.insert(0, str(HERE))
import specs  # noqa: E402


def plan_maps(lesson):
    txt = (SRC / f"l{lesson}/scenePlan.ts").read_text(encoding="utf-8")
    out = {}
    for name, body in zip(*[iter(re.split(r"export const (\w+)[^=]*=", txt)[1:])] * 2):
        out[name] = dict(re.findall(r'"([^"]+)"\s*:\s*"(\w+)"', body))
    return out


def main():
    lid = sys.argv[1]
    spec = getattr(specs, lid)
    L = REPO / "lessons" / lid
    chs = [json.loads(p.read_text(encoding="utf-8")) for p in sorted((L / "script/chapters").glob("ch*.json"))]
    tl = json.loads((SRC / f"l{lid}/timeline.json").read_text(encoding="utf-8"))
    tl_scenes = {s["id"]: s for s in tl["scenes"]}
    plans = {k: plan_maps(k) for k in ("001", "002")}
    boards, vis, line, scene_cut = [], {}, {}, {}
    used_origin_keys = {}
    for ch in chs:
        for s in ch["scenes"]:
            first = next((b for b in s["beats"] if b.get("origin", "new") != "new"), None)
            sref = None
            orig_scene = [b["origin"].split("#")[0] for b in s["beats"] if b.get("origin", "new") != "new"]
            spec_ch = next(c for c in spec["chapters"] if c["id"] == ch["id"])
            idx = int(s["id"].split("-s")[1]) - 1
            ref, op = spec_ch["scenes"][idx]
            if ref == "new":
                boards.append(f'  "{s["id"]}": NB["{lid}-{s["id"]}"],')
            else:
                Ls, sid = ref.split(":")
                over = spec.get("boards", {}).get(s["id"])
                boards.append(f'  "{s["id"]}": {over or f"B{Ls}[\"{sid}\"]"},')
                if sid in plans[Ls].get("sceneCutaways", {}):
                    scene_cut[s["id"]] = plans[Ls]["sceneCutaways"][sid]
            for i, b in enumerate(s["beats"]):
                o = b.get("origin", "new")
                if o == "new":
                    continue
                Ls, okey = o.split(":")
                key = f"{s['id']}#{i}"
                if okey in plans[Ls].get("visualCutaways", {}) and b["type"] == "visual":
                    vis[key] = plans[Ls]["visualCutaways"][okey]
                if okey in plans[Ls].get("lineCutaways", {}) and b["type"] == "line" and not b.get("revoiced"):
                    line[key] = plans[Ls]["lineCutaways"][okey]
    # star chapters: count star-lighting visual beats
    star_re = lambda t: bool(re.search("жылдыз", t, re.I) and re.search("жан|жаркыра|жылт", t, re.I))
    n_labels = len(spec["meta"]["starLabels"])
    lit, starsLit = 0, {}
    for c in tl["chapters"]:
        for s in tl["scenes"]:
            if s["chapter"] == c["id"]:
                lit += sum(1 for b in s["beats"] if b["type"] == "visual" and star_re(b["text"]))
        starsLit[c["id"]] = lit  # may exceed the label count (e.g. "all stars shine" beats): avoids a dip before such a beat
    c = json.loads((REPO / f"shared/lesson-cover/lessons/{int(lid[1:]):03d}.json").read_text(encoding="utf-8"))
    cover = {"number": c["number"], "topic": c["topic"]}
    out = SRC / f"l{lid}"
    out.mkdir(exist_ok=True)
    m = spec["meta"]
    last_scene = tl["scenes"][-1]["id"]
    (out / "meta.ts").write_text(
        'import type { LessonMeta } from "../active";\n\n'
        f"// Generated by production/vid-002-rework/remotion_data.py — VID-002 rework {lid}.\n"
        "export const meta: LessonMeta = {\n"
        f'  id: "{lid}",\n  kicker: {json.dumps(m["kicker"], ensure_ascii=False)},\n  title: {json.dumps(m["title"], ensure_ascii=False)},\n'
        f'  subtitle: {json.dumps(m["subtitle"], ensure_ascii=False)},\n'
        '  previewNote: "",  // FINAL_VIDEO_USTAZ_REVIEW_RULES.md: no review status in the video\n'
        f'  starLabels: {json.dumps(m["starLabels"], ensure_ascii=False)},\n  lastScene: "{last_scene}",\n'
        '  endNote: "",\n'
        f'  cover: {json.dumps(cover, ensure_ascii=False)},\n'
        "};\n"
        f"export const starsLit: Record<string, number> = {json.dumps(starsLit)};\n"
        "export const newStarChapters = new Set<string>();\n", encoding="utf-8")
    (out / "boardPlans.ts").write_text(
        'import type { Row } from "../../art/boardTypes";\nimport { T, I } from "../../art/boardTypes";\n'
        'import { boardPlans as B001 } from "../l001/boardPlans";\nimport { boardPlans as B002 } from "../l002/boardPlans";\n'
        'import { newBoards as NB } from "../rework/newBoards";\n\n'
        f"// Generated by production/vid-002-rework/remotion_data.py: boards of {lid} are the approved boards of the origin scenes\n"
        "// (lessons/001, lessons/002) or new boards (../rework/newBoards.ts).\n"
        "void T; void I;\n"
        "export const boardPlans: Record<string, Row[]> = {\n" + "\n".join(boards) + "\n};\n", encoding="utf-8")
    fmt = lambda d: "\n".join(f'  "{k}": "{v}",' for k, v in d.items())
    (out / "scenePlan.ts").write_text(
        'import type { CutawayId } from "../../art/cutawayIds";\n\n'
        f"// Generated by production/vid-002-rework/remotion_data.py: illustrations inherited from the approved lessons by beat origin.\n"
        "// Allah, the Prophet (с.а.в.), companions, prophets and angels are never shown.\n"
        f"export const visualCutaways: Record<string, CutawayId> = {{\n{fmt(vis)}\n}};\n"
        f"export const sceneCutaways: Record<string, CutawayId> = {{\n{fmt(scene_cut)}\n}};\n"
        f"export const lineCutaways: Record<string, CutawayId> = {{\n{fmt(line)}\n}};\n", encoding="utf-8")
    (out / "index.ts").write_text(
        (SRC / "l001/index.ts").read_text(encoding="utf-8").replace("lesson001", f"lesson{lid}"), encoding="utf-8")
    print(f"{lid}: {len(boards)} boards, {len(vis)} visual + {len(line)} line cutaways, starsLit {starsLit}")


if __name__ == "__main__":
    main()
