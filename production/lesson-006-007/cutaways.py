def beats(lid):
    meta = json.loads((ROOT / f"lessons/{lid}/script/lesson.json").read_text(encoding="utf-8"))
    for c in meta["chapters"]:
        ch = json.loads((ROOT / f"lessons/{lid}/script/chapters/{c}.json").read_text(encoding="utf-8"))
        for s in ch["scenes"]:
            for i, b in enumerate(s["beats"]):
                yield f"{s['id']}#{i}", b


def main():
    out = {"visual": {}, "line": {}}
    for lid, spec in SPEC.items():
        allb = list(beats(lid))
        for kind, frag, cid in spec:
            hits = [k for k, b in allb if (b["type"] == "visual" and kind == "visual" and frag in b["description"])
                    or (b["type"] == "line" and kind == "line" and b["speaker"] == "ustaz" and frag in b["text"])]
            if len(hits) != 1:
                sys.exit(f"{lid}: '{frag}' matched {hits}")
            out[kind][hits[0]] = cid
    ts = ["// GENERATED by production/lesson-006-007/cutaways.py — do not edit by hand.",
          'import type { CutawayId } from "./scenePlan";', ""]
    ts.append("export const visual67: Record<string, CutawayId> = {")
    ts += [f'  "{k}": "{v}",' for k, v in out["visual"].items()] + ["};", ""]
    ts.append("export const scene67: Record<string, CutawayId> = {};\n")
    ts.append("export const line67: Record<string, CutawayId> = {")
    ts += [f'  "{k}": "{v}",' for k, v in out["line"].items()] + ["};", ""]
    (ROOT / "video/src/art/scenePlan67.ts").write_text("\n".join(ts), encoding="utf-8")
    print(f"scenePlan67.ts: {len(out['visual'])} visual, {len(out['line'])} line cutaways")


if __name__ == "__main__":
    main()
