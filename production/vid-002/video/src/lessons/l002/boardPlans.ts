// The ﷺ ligature is not in the board font, so the board writes "(с.а.в.)" instead.

const STARS = ["ИСЛАМ", "ЫЙМАН", "ИХСАН"];
// The recurring picture: three stars ИСЛАМ · ЫЙМАН · ИХСАН. Lit ones are gold stars, unlit ones outlines.
const stars3 = (lit: number, size = 70, labels: string[] = STARS): Row =>
  STARS.map((_, i) => I(i < lit ? "star" : "starOutline", (i < lit ? "y" : "k") as Col, labels[i], size));
// One star with its word, used inline.
const star = (i: number, lit: boolean, size = 56): Tok => I(lit ? "star" : "starOutline", lit ? "y" : "k", STARS[i], size);

// Lesson 1 recap: the roof «ИСЛАМ» over five columns.
const PILLARS = ["ШАХАДА", "НАМАЗ", "ЗЕКЕТ", "ОРОЗО", "АЖЫЛЫК"];
