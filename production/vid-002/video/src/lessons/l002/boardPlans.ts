const cols = (labels: string[] = PILLARS, size = 86, c: Col = "b"): Row => labels.map((l) => I("column", c, l, size));
// Six circles of the pillars of iman.
const circle = (n: number, word: string, size = 76, ts = 50): Tok[] => [I("circle", "g", undefined, size), T(`${n}. ${word}`, "g", ts)];

